def main():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    sym_dir = os.path.join(base_dir, "symbols")
    sub_sch_path = os.path.join(base_dir, "sziklaiN.sch")
    sub_png_path = os.path.join(base_dir, "sziklaiN.png")
    sch_path = os.path.join(base_dir, "fancontrol_sziklai.sch")
    png_path = os.path.join(base_dir, "fancontrol_sziklai.png")
    net_path = os.path.join(base_dir, "fancontrol_sziklai.net")

    create_symbols(sym_dir)
    build_sziklai_subcircuit(sub_sch_path)
    build_schematic(sch_path)

    # Export PNGs
    print("Exporting sziklaiN.sch preview PNG...")
    res_sub_png = subprocess.run(["lepton-cli", "export", "-o", sub_png_path, sub_sch_path], capture_output=True, text=True)
    if res_sub_png.returncode == 0:
        print(f"Exported subcircuit PNG successfully: {sub_png_path}")
    else:
        print(f"Error exporting subcircuit PNG: {res_sub_png.stderr}")

    print("Exporting fancontrol_sziklai.sch preview PNG...")
    res = subprocess.run(["lepton-cli", "export", "-o", png_path, sch_path], capture_output=True, text=True)
    if res.returncode == 0:
        print(f"Exported top-level PNG successfully: {png_path}")
    else:
        print(f"Error exporting top-level PNG: {res.stderr}")

    # Export Netlist
    print("Compiling Netlist...")
    res_net = subprocess.run(["lepton-netlist", "-g", "PCB", "-o", net_path, sch_path], capture_output=True, text=True)
    if res_net.returncode == 0:
        print(f"Compiled Netlist successfully: {net_path}")
    else:
        print(f"Error compiling netlist: {res_net.stderr}")

if __name__ == "__main__":
    main()
